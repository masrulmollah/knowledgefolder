# TAB 3 — INTERACTIVE EXERCISES
# ================================================================================
with tabs[2]:
    st.subheader("✏️ Interactive Exercise — Build a Cash Flow Statement (Indirect Method)")
    st.markdown(
        "Adjust the drivers on the left. Watch net income get converted into **real cash**, split across "
        "Operating, Investing and Financing — and see the closing cash balance update live."
    )

    left, right = st.columns([0.34, 0.66])

    with left:
        st.markdown("##### 🧾 From the P&L")
        net_income = st.number_input("Net income (€)", -1_000_000, 5_000_000, 231_000, 10_000)
        depreciation = st.number_input("Depreciation (add-back) (€)", 0, 2_000_000, 120_000, 10_000)

        st.markdown("##### 💧 Working capital changes")
        d_receivables = st.number_input("Δ Receivables (€)", -1_000_000, 1_000_000, 46_575, 5_000,
                                        help="Increase = uses cash")
        d_inventory = st.number_input("Δ Inventory (€)", -1_000_000, 1_000_000, 27_260, 5_000,
                                     help="Increase = uses cash")
        d_payables = st.number_input("Δ Payables (€)", -1_000_000, 1_000_000, 18_630, 5_000,
                                    help="Increase = source of cash")

        st.markdown("##### 🏭 Investing")
        capex = st.number_input("Capex (€)", 0, 5_000_000, 200_000, 25_000)
        asset_sales = st.number_input("Asset sales (€)", 0, 5_000_000, 0, 25_000)

        st.markdown("##### 🏦 Financing")
        new_debt = st.number_input("New debt raised (€)", 0, 10_000_000, 100_000, 25_000)
        debt_repay = st.number_input("Debt repayments (€)", 0, 10_000_000, 0, 25_000)
        equity_issued = st.number_input("Equity issued (€)", 0, 10_000_000, 0, 25_000)
        dividends = st.number_input("Dividends paid (€)", 0, 5_000_000, 50_000, 10_000)

        st.markdown("##### 🏁 Opening position")
        opening_cash = st.number_input("Opening cash (€)", -1_000_000, 10_000_000, 150_000, 10_000)

    with right:
        # CFO (indirect)
        cfo = net_income + depreciation - d_receivables - d_inventory + d_payables
        # CFI
        cfi = -capex + asset_sales
        # CFF
        cff = new_debt - debt_repay + equity_issued - dividends
        # Reconcile
        net_change = cfo + cfi + cff
        closing_cash = opening_cash + net_change
        fcf = cfo - capex

        k1, k2, k3 = st.columns(3)
        k1.metric("Operating (CFO)", money(cfo))
        k2.metric("Investing (CFI)", money(cfi))
        k3.metric("Financing (CFF)", money(cff))

        k4, k5, k6 = st.columns(3)
        k4.metric("Net change in cash", money(net_change))
        k5.metric("Closing cash", money(closing_cash),
                  "⚠️ Negative!" if closing_cash < 0 else None,
                  delta_color="inverse" if closing_cash < 0 else "normal")
        k6.metric("Free Cash Flow", money(fcf), help="CFO − Capex")

        if closing_cash < 0:
            st.error(
                f"⚠️ **Closing cash is negative ({money(closing_cash)}).** The business would run out of cash "
                "— it needs more financing, lower capex, or better working-capital management."
            )
        elif cfo < 0:
            st.warning(
                "🔎 **Operating cash flow is negative** — the core business is burning cash before any "
                "investment or financing. Watch this closely."
            )
        else:
            st.success(f"✅ Healthy: the business generated **{money(cfo)}** of operating cash this period.")

        # Statement table
        cf = pd.DataFrame(
            {
                "Cash Flow Statement (Indirect Method)": [
                    "Net income",
                    "  + Depreciation (non-cash)",
                    "  − Δ Receivables",
                    "  − Δ Inventory",
                    "  + Δ Payables",
                    "= Cash Flow from Operations (CFO)",
                    "  − Capex",
                    "  + Asset sales",
                    "= Cash Flow from Investing (CFI)",
                    "  + New debt",
                    "  − Debt repayments",
                    "  + Equity issued",
                    "  − Dividends",
                    "= Cash Flow from Financing (CFF)",
                    "Net change in cash",
                    "Opening cash",
                    "= Closing cash",
                ],
                "€": [
                    net_income, depreciation, -d_receivables, -d_inventory, d_payables, cfo,
                    -capex, asset_sales, cfi,
                    new_debt, -debt_repay, equity_issued, -dividends, cff,
                    net_change, opening_cash, closing_cash,
                ],
            }
        )
        cf["€"] = cf["€"].map(lambda v: money(v))
        st.markdown("##### 📄 Cash Flow Statement")
        st.dataframe(cf, use_container_width=True, hide_index=True)

    st.markdown("---")
    st.markdown("##### 🧪 Try these challenges")
    e1, e2 = st.columns(2)
    with e1:
        st.markdown(
            """
1. **Profit ≠ cash:** Set net income to €231k but push Δ Receivables to €400k. Watch CFO turn negative
   despite a healthy profit.
2. **Depreciation add-back:** Raise depreciation to €500k. See CFO rise even though profit is unchanged.
"""
        )
    with e2:
        st.markdown(
            """
3. **Capex crunch:** Push capex to €1,000,000. Does closing cash go negative? How would you fund the gap?
4. **Free cash flow:** Find the combination where FCF (CFO − Capex) is exactly zero.
"""
        )

    st.download_button(
        "⬇️ Download this cash flow statement (CSV)",
        cf.to_csv(index=False).encode("utf-8"),
        "cash_flow_statement.csv",
        "text/csv",
    )

