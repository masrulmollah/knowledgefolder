# TAB 1 — THEORY & CONCEPTS
# ================================================================================
with tabs[0]:
    st.subheader("Theory & Concepts")

    st.markdown(
        """
### The three sections of a cash flow statement
Every cash flow statement splits movements into three activities, then ties to the change in cash:
"""
    )

    sections = pd.DataFrame(
        {
            "Section": ["Cash Flow from Operations (CFO)", "Cash Flow from Investing (CFI)",
                        "Cash Flow from Financing (CFF)"],
            "Captures": [
                "Cash generated by the core business (day-to-day trading)",
                "Buying/selling long-term assets (capex, acquisitions, disposals)",
                "Raising/repaying capital (debt draws & repayments, equity, dividends)",
            ],
            "Typical items": [
                "Net income, + depreciation, ± working capital changes",
                "− Capex, − acquisitions, + asset sales",
                "+ New debt, − repayments, + equity issued, − dividends",
            ],
        }
    )
    st.table(sections)

    st.markdown(
        """
### The indirect method (start from profit, adjust to cash)
The indirect method builds **Cash Flow from Operations** like this:
"""
    )
    st.latex(r"CFO = \text{Net Income} + \text{Depreciation} \pm \Delta\text{Working Capital}")

    st.markdown(
        """
Then the full statement reconciles to the movement in cash:

$$\\Delta\\text{Cash} = CFO + CFI + CFF$$

$$\\text{Closing Cash} = \\text{Opening Cash} + \\Delta\\text{Cash}$$
"""
    )

    with st.expander("🔑 Concept 1 — Add back non-cash items (depreciation)"):
        st.markdown(
            """
Depreciation was subtracted on the income statement, but **no cash actually left** the business — it's
an accounting allocation of past capex. So we **add it back** to net income. The same applies to
amortisation and other non-cash charges.

> Net income understates cash by the amount of non-cash charges — adding them back corrects this.
"""
        )

    with st.expander("🔑 Concept 2 — Working capital changes (the timing effect)"):
        st.markdown(
            """
Changes in working capital move cash **opposite** to the balance-sheet change:

| If this goes UP… | Effect on cash |
|---|---|
| Receivables ↑ (customers owe more) | Cash ↓ (uses cash) |
| Inventory ↑ (more stock held) | Cash ↓ (uses cash) |
| Payables ↑ (you owe suppliers more) | Cash ↑ (source of cash) |

$$\\Delta WC = \\Delta\\text{Receivables} + \\Delta\\text{Inventory} - \\Delta\\text{Payables}$$

An **increase** in net working capital **consumes** cash (subtract it); a decrease releases cash.
"""
        )

    with st.expander("🔑 Concept 3 — Capex sits in Investing, not Operating"):
        st.markdown(
            """
Buying equipment is a real cash outflow, but it belongs in **Investing (CFI)**, not Operations. This
separation lets readers see whether the *core business* generates cash (CFO) before the effects of
investment and financing decisions.

**Free Cash Flow (FCF)** = CFO − Capex — a key measure used throughout valuation (Part 3).
"""
        )

    with st.expander("🔑 Concept 4 — How cash flow links the three statements"):
        st.markdown(
            """
The cash flow statement is the **glue** of the three-statement model:
- **Net income** comes from the *income statement*.
- **Depreciation, working-capital changes, capex, debt & dividends** come from the *balance sheet* movements.
- The **closing cash** it calculates flows straight back onto the *balance sheet*.

If everything is linked correctly, the balance sheet balances automatically (see Module 1.4).
"""
        )

    st.success(
        "**Takeaway:** The indirect method starts from net income, adds back non-cash items, adjusts for "
        "working-capital timing, then layers investing and financing flows to explain the change in cash."
    )

