# TAB 2 — WORKED EXAMPLES
# ================================================================================
with tabs[1]:
    st.subheader("Worked Example — From profit to cash, step by step")
    st.markdown("Continuing our fictional company **'CleanSoap'** from the previous modules.")

    st.markdown("#### Starting point (from the income statement & balance sheet)")
    st.markdown(
        """
| Item | Value |
|---|---|
| Net income | €231,000 |
| Depreciation (non-cash) | €120,000 |
| Increase in receivables | €46,575 |
| Increase in inventory | €27,260 |
| Increase in payables | €18,630 |
| Capex | €200,000 |
| New long-term debt | €100,000 |
| Dividends paid | €50,000 |
| Opening cash | €150,000 |
"""
    )

    st.markdown("#### Step 1 — Cash Flow from Operations (indirect method)")
    st.markdown(
        """
| Line | Calculation | € |
|---|---|---|
| Net income | | 231,000 |
| + Depreciation | add back non-cash | 120,000 |
| − Increase in receivables | uses cash | (46,575) |
| − Increase in inventory | uses cash | (27,260) |
| + Increase in payables | source of cash | 18,630 |
| **= Cash Flow from Operations** | | **€295,795** |
"""
    )

    st.markdown("#### Step 2 — Investing & Financing")
    st.markdown(
        """
| Section | Item | € |
|---|---|---|
| **Investing (CFI)** | − Capex | (200,000) |
| **Financing (CFF)** | + New debt | 100,000 |
| | − Dividends | (50,000) |
| | **CFF subtotal** | **50,000** |
"""
    )

    st.markdown("#### Step 3 — Reconcile to closing cash")
    col1, col2, col3 = st.columns(3)
    col1.metric("CFO", "€295,795")
    col2.metric("CFI", "-€200,000")
    col3.metric("CFF", "€50,000")

    st.markdown(
        """
$$\\Delta\\text{Cash} = 295{,}795 - 200{,}000 + 50{,}000 = \\mathbf{€145{,}795}$$
$$\\text{Closing Cash} = 150{,}000 + 145{,}795 = \\mathbf{€295{,}795}$$
"""
    )

    st.info(
        "**Insight:** Net income was €231k, but the business actually generated **€296k of operating cash** "
        "(thanks to the €120k depreciation add-back), and ended with €296k cash despite spending €200k on "
        "capex. **This is why profit ≠ cash** — and why the cash flow statement is essential."
    )

